"""
The `r65.lock` lockfile: the version and commit each package resolved to.

    [[package]]
    name    = "stdlib"
    version = "0.4.2"
    source  = "git+https://github.com/BubbleZapGames/R65?tag=stdlib-v0.4.2"
    rev     = "0bf2f0f4a1..."

A path dependency or patched package has `source = "path+<dir>"` (relative to
the lockfile) and no rev. A git package with no rev is one `r65x init` copied
from the installed r65 rather than cloned: it names the release it is, and the
first fetch that has to clone it - or an update - pins the commit. Reading is
for `r65c`; writing is `r65pkg`'s.
"""

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Optional, Tuple

from r65.pkg.manifest import PackageError
from r65.pkg.version import Version, VersionError, format_version, parse_version

LOCK_FILENAME = "r65.lock"
LOCK_FORMAT = 1


@dataclass(frozen=True)
class LockedPackage:
    name: str
    version: Version
    source: str
    rev: Optional[str] = None

    @property
    def is_git(self) -> bool:
        return self.source.startswith("git+")

    @property
    def git_url(self) -> Optional[str]:
        return self.source[4:].rpartition("?")[0] if self.is_git else None

    @property
    def ref(self) -> Optional[Tuple[str, str]]:
        """(kind, value) of the git ref the source names: tag, rev or branch."""
        if not self.is_git:
            return None
        kind, _, value = self.source.rpartition("?")[2].partition("=")
        return kind, value

    @property
    def path(self) -> Optional[str]:
        return self.source[5:] if self.source.startswith("path+") else None


def git_source(url: str, kind: str, value: str) -> str:
    return f"git+{url}?{kind}={value}"


def read_lock(path) -> Dict[str, LockedPackage]:
    path = Path(path)
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except OSError as e:
        raise PackageError(f"{path}: cannot read: {e.strerror or e}")
    except tomllib.TOMLDecodeError as e:
        raise PackageError(f"{path}: invalid TOML: {e}")
    if data.get("version") != LOCK_FORMAT:
        raise PackageError(f"{path}: unsupported lockfile format "
                           f"{data.get('version')!r}; regenerate it with `r65pkg update`")
    locked: Dict[str, LockedPackage] = {}
    for entry in data.get("package", []):
        try:
            pkg = LockedPackage(name=entry["name"], version=parse_version(entry["version"]),
                                source=entry["source"], rev=entry.get("rev"))
        except (KeyError, TypeError, VersionError) as e:
            raise PackageError(f"{path}: malformed [[package]] entry {entry!r}: {e}")
        if not (pkg.is_git or pkg.path is not None):
            raise PackageError(f"{path}: malformed [[package]] entry for '{pkg.name}'")
        locked[pkg.name] = pkg
    return locked


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lock(path, packages: Dict[str, LockedPackage]) -> None:
    lines = ["# Generated by r65pkg: do not edit by hand.", f"version = {LOCK_FORMAT}"]
    for name in sorted(packages):
        pkg = packages[name]
        lines += ["", "[[package]]",
                  f"name    = {_quote(pkg.name)}",
                  f"version = {_quote(format_version(pkg.version))}",
                  f"source  = {_quote(pkg.source)}"]
        if pkg.rev:
            lines.append(f"rev     = {_quote(pkg.rev)}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
